import pandas as pd


# ============================================================
# 0. 파일 경로 설정
# ============================================================

# 월세 원본 데이터
INPUT_FILE = r"C:\Users\과표사업단\Downloads\싱글벙글\서울특별시_전월세가\서울특별시_전월세가_2025.csv"

# 법정동 → 행정동 매핑 데이터
MAPPING_FILE = r"C:\Users\과표사업단\Downloads\싱글벙글\행정동코드_법정동코드.xlsx"

# 최종 결과
OUTPUT_FILE = "월세데이터_행정동코드추가.csv"

# 매핑 실패 데이터
FAILED_FILE = "월세데이터_행정동매핑실패.csv"


# ============================================================
# 1. 월세 데이터 불러오기
# ============================================================

df = pd.read_csv(
    INPUT_FILE,
    encoding="cp949",
    dtype={
        "자치구코드": "string",
        "법정동코드": "string"
    }
)

print("=" * 60)
print("월세 데이터 불러오기")
print("=" * 60)
print(f"전체 행 수: {len(df):,}")
print(df.columns.tolist())


# ============================================================
# 2. 원본 코드 문자열 정리
# ============================================================

# ------------------------------------------------------------
# 자치구코드
# ------------------------------------------------------------
# 반드시 문자열로 변환한 뒤 공백 제거
df["자치구코드"] = (
    df["자치구코드"]
    .astype("string")
    .str.strip()
    .str.replace(r"\.0$", "", regex=True)
)

# 자치구코드가 5자리 숫자가 되도록 앞에 0을 채움
df["자치구코드"] = df["자치구코드"].str.zfill(5)


# ------------------------------------------------------------
# 법정동코드
# ------------------------------------------------------------
# 반드시 문자열로 변환한 뒤 공백 제거
df["법정동코드"] = (
    df["법정동코드"]
    .astype("string")
    .str.strip()
    .str.replace(r"\.0$", "", regex=True)
)

# 법정동코드도 5자리로 맞춤
df["법정동코드"] = df["법정동코드"].str.zfill(5)


# ============================================================
# 3. 자치구코드 + 법정동코드 → 열자리코드 생성
# ============================================================

# ------------------------------------------------------------
# 중요:
# 자치구코드 5자리 + 법정동코드 5자리
# = 10자리 열자리코드
#
# 두 컬럼 모두 문자열 상태에서 결합
# ------------------------------------------------------------

df["열자리코드"] = (
    df["자치구코드"]
    + df["법정동코드"]
)


# ============================================================
# 4. 열자리코드 생성 결과 확인
# ============================================================

print("\n" + "=" * 60)
print("열자리코드 생성 확인")
print("=" * 60)

print("\n[원본 코드 → 열자리코드 예시]")

print(
    df[
        [
            "자치구코드",
            "법정동코드",
            "열자리코드",
            "법정동명"
        ]
    ]
    .head(20)
)


# ============================================================
# 5. 열자리코드 유효성 검증
# ============================================================

invalid_code = df[
    df["열자리코드"].isna()
    |
    ~df["열자리코드"].str.fullmatch(r"\d{10}", na=False)
].copy()

print("\n[열자리코드 검증]")

print(
    f"전체 행: {len(df):,}"
)

print(
    f"열자리코드 정상: "
    f"{len(df) - len(invalid_code):,}"
)

print(
    f"열자리코드 이상/결측: "
    f"{len(invalid_code):,}"
)


# ============================================================
# 6. 자치구코드 / 법정동코드 자체 검증
# ============================================================

invalid_gu = df[
    ~df["자치구코드"].str.fullmatch(r"\d{5}", na=False)
].copy()

invalid_bjd = df[
    ~df["법정동코드"].str.fullmatch(r"\d{5}", na=False)
].copy()

print("\n[5자리 코드 검증]")

print(
    f"자치구코드 이상/결측: "
    f"{len(invalid_gu):,}"
)

print(
    f"법정동코드 이상/결측: "
    f"{len(invalid_bjd):,}"
)


# ============================================================
# 7. 법정동 → 행정동 매핑 데이터 불러오기
# ============================================================

mapping = pd.read_excel(MAPPING_FILE)

print("\n" + "=" * 60)
print("법정동 → 행정동 매핑 데이터")
print("=" * 60)

print(
    f"매핑 데이터 행 수: {len(mapping):,}"
)

print(
    mapping.columns.tolist()
)


# ============================================================
# 8. 매핑 데이터 코드 정리
# ============================================================

# 매핑 데이터의 법정동코드는 이미 10자리 코드이므로
# 열자리코드라는 이름으로 변경하여 사용

mapping["열자리코드"] = (
    mapping["법정동코드"]
    .astype("string")
    .str.strip()
    .str.replace(r"\.0$", "", regex=True)
    .str.zfill(10)
)

mapping["행정동코드"] = (
    mapping["행정동코드"]
    .astype("string")
    .str.strip()
    .str.replace(r"\.0$", "", regex=True)
    .str.zfill(10)
)


# ============================================================
# 9. 매핑 데이터 열자리코드 검증
# ============================================================

invalid_mapping_code = mapping[
    ~mapping["열자리코드"].str.fullmatch(
        r"\d{10}",
        na=False
    )
].copy()

print("\n[매핑 데이터 열자리코드 검증]")

print(
    f"정상: "
    f"{len(mapping) - len(invalid_mapping_code):,}"
)

print(
    f"이상/결측: "
    f"{len(invalid_mapping_code):,}"
)


# ============================================================
# 10. 매핑 데이터에서 필요한 컬럼만 선택
# ============================================================

mapping = mapping[
    [
        "열자리코드",
        "행정동코드",
        "시도명",
        "시군구명",
        "읍면동명"
    ]
].copy()


# ============================================================
# 11. 열자리코드 → 행정동코드 관계 확인
# ============================================================

code_check = (
    mapping
    .groupby("열자리코드")["행정동코드"]
    .nunique()
)

print("\n" + "=" * 60)
print("열자리코드 → 행정동 관계 확인")
print("=" * 60)

print(
    "열자리코드 하나당 행정동코드 개수:"
)

print(
    code_check
    .value_counts()
    .sort_index()
)


# ============================================================
# 12. 하나의 열자리코드가 여러 행정동으로 매핑되는 경우
# ============================================================

multiple_admin = code_check[
    code_check > 1
]

print(
    f"\n여러 행정동으로 매핑되는 열자리코드: "
    f"{len(multiple_admin):,}개"
)

if len(multiple_admin) > 0:

    print("\n[여러 행정동으로 매핑되는 사례]")

    print(
        mapping[
            mapping["열자리코드"].isin(
                multiple_admin.index
            )
        ]
        .sort_values("열자리코드")
        .head(50)
    )


# ============================================================
# 13. 중복 매핑 제거
# ============================================================

mapping_unique = (
    mapping
    .drop_duplicates(
        subset=[
            "열자리코드",
            "행정동코드"
        ]
    )
    .copy()
)


# ============================================================
# 14. 열자리코드 → 행정동코드 JOIN
# ============================================================

result = df.merge(
    mapping_unique,
    on="열자리코드",
    how="left",
    suffixes=("", "_매핑")
)


# ============================================================
# 15. 행정동 매핑 결과 확인
# ============================================================

print("\n" + "=" * 60)
print("행정동 매핑 결과")
print("=" * 60)

print(
    f"전체 월세 데이터: {len(result):,}"
)

print(
    f"행정동 매칭 성공: "
    f"{result['행정동코드'].notna().sum():,}"
)

print(
    f"행정동 매칭 실패: "
    f"{result['행정동코드'].isna().sum():,}"
)


# ============================================================
# 16. 매칭률 계산
# ============================================================

total = len(result)

matched = (
    result["행정동코드"]
    .notna()
    .sum()
)

match_rate = (
    matched / total * 100
    if total > 0
    else 0
)

print(
    f"\n행정동 매칭률: "
    f"{match_rate:.2f}%"
)


# ============================================================
# 17. 매칭 실패 데이터 확인
# ============================================================

failed = result[
    result["행정동코드"].isna()
].copy()

print("\n[행정동 매칭 실패 열자리코드]")

print(
    failed[
        [
            "자치구코드",
            "법정동코드",
            "열자리코드",
            "법정동명"
        ]
    ]
    .drop_duplicates()
    .head(50)
)


# ============================================================
# 18. 매칭 실패 데이터 저장
# ============================================================

failed.to_csv(
    FAILED_FILE,
    index=False,
    encoding="utf-8-sig"
)


# ============================================================
# 19. 최종 컬럼 정리
# ============================================================

drop_columns = [
    "시도명",
    "시군구명"
]

for col in drop_columns:

    if col in result.columns:

        result.drop(
            columns=col,
            inplace=True
        )


# ============================================================
# 20. 최종 데이터 저장
# ============================================================

result.to_csv(
    OUTPUT_FILE,
    index=False,
    encoding="utf-8-sig"
)


# ============================================================
# 21. 최종 결과 출력
# ============================================================

print("\n" + "=" * 60)
print("완료!")
print("=" * 60)

print(
    f"최종 데이터: {OUTPUT_FILE}"
)

print(
    f"매칭 실패 데이터: {FAILED_FILE}"
)

print(
    f"최종 행 수: {len(result):,}"
)

print("\n[최종 데이터 예시]")

print(
    result[
        [
            "자치구코드",
            "법정동코드",
            "열자리코드",
            "법정동명",
            "행정동코드",
            "읍면동명"
        ]
    ].head(20)
)