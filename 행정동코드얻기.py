import pandas as pd


# ============================================================
# 0. 파일 경로 설정
# ============================================================

# 월세 원본 데이터
INPUT_FILE = r"C:\Users\과표사업단\Downloads\싱글벙글\서울특별시_전월세가\서울특별시_전월세가_2025.csv"

# 법정동 → 행정동 매핑 데이터
MAPPING_FILE = r"C:\Users\과표사업단\Downloads\싱글벙글\행정동코드_법정동코드.xlsx"

# 최종 결과
OUTPUT_FILE = "월세데이터_행정동코드추가.csv"

# 매핑 실패 데이터
FAILED_FILE = "월세데이터_행정동매핑실패.csv"


# ============================================================
# 1. 월세 데이터 불러오기
# ============================================================

df = pd.read_csv(
    INPUT_FILE,
    encoding="cp949",
    dtype={
        "자치구코드": "string",
        "법정동코드": "string"
    }
)

print("=" * 60)
print("월세 데이터 불러오기")
print("=" * 60)

print(f"전체 행 수: {len(df):,}")
print(df.columns.tolist())


# ============================================================
# 2. 법정동코드 정리
# ============================================================

# 법정동코드가 이미 존재한다면 우선 사용
if "법정동코드" in df.columns:

    df["법정동코드"] = (
        df["법정동코드"]
        .astype("string")
        .str.strip()
    )

else:
    print("법정동코드 컬럼이 없습니다.")


# ============================================================
# 3. 법정동코드 10자리로 통일
# ============================================================

# 숫자처럼 저장되어 있던 코드의 소수점 제거
df["법정동코드"] = (
    df["법정동코드"]
    .str.replace(r"\.0$", "", regex=True)
    .str.zfill(10)
)

print("\n[법정동코드 예시]")
print(
    df["법정동코드"]
    .drop_duplicates()
    .head(20)
)


# ============================================================
# 4. 법정동코드 유효성 확인
# ============================================================

# 10자리 숫자인지 확인
invalid_code = df[
    df["법정동코드"].isna()
    |
    ~df["법정동코드"].str.fullmatch(r"\d{10}", na=False)
].copy()

print("\n[법정동코드 검증]")
print(
    f"전체 행: {len(df):,}"
)

print(
    f"법정동코드 정상: "
    f"{len(df) - len(invalid_code):,}"
)

print(
    f"법정동코드 이상/결측: "
    f"{len(invalid_code):,}"
)


# ============================================================
# 5. 법정동 → 행정동 매핑 데이터 불러오기
# ============================================================

mapping = pd.read_excel(MAPPING_FILE)

print("\n" + "=" * 60)
print("법정동 → 행정동 매핑 데이터")
print("=" * 60)

print(f"매핑 데이터 행 수: {len(mapping):,}")
print(mapping.columns.tolist())


# ============================================================
# 6. 매핑 데이터 코드 정리
# ============================================================

mapping["법정동코드"] = (
    mapping["법정동코드"]
    .astype("string")
    .str.strip()
    .str.replace(r"\.0$", "", regex=True)
    .str.zfill(10)
)

mapping["행정동코드"] = (
    mapping["행정동코드"]
    .astype("string")
    .str.strip()
    .str.replace(r"\.0$", "", regex=True)
    .str.zfill(10)
)


# ============================================================
# 7. 매핑 데이터에서 필요한 컬럼만 선택
# ============================================================

mapping = mapping[
    [
        "법정동코드",
        "행정동코드",
        "시도명",
        "시군구명",
        "읍면동명"
    ]
].copy()


# ============================================================
# 8. 법정동코드 → 행정동코드 관계 확인
# ============================================================

code_check = (
    mapping
    .groupby("법정동코드")["행정동코드"]
    .nunique()
)

print("\n" + "=" * 60)
print("법정동 → 행정동 관계 확인")
print("=" * 60)

print("법정동코드 하나당 행정동코드 개수:")

print(
    code_check.value_counts()
    .sort_index()
)


# ============================================================
# 9. 하나의 법정동코드가 여러 행정동으로 매핑되는 경우 확인
# ============================================================

multiple_admin = code_check[
    code_check > 1
]

print(
    f"\n여러 행정동으로 매핑되는 법정동코드: "
    f"{len(multiple_admin):,}개"
)

if len(multiple_admin) > 0:

    print("\n[여러 행정동으로 매핑되는 사례]")

    print(
        mapping[
            mapping["법정동코드"].isin(
                multiple_admin.index
            )
        ]
        .sort_values("법정동코드")
        .head(50)
    )


# ============================================================
# 10. 중복 매핑 제거
# ============================================================

mapping_unique = (
    mapping
    .drop_duplicates(
        subset=[
            "법정동코드",
            "행정동코드"
        ]
    )
    .copy()
)


# ============================================================
# 11. 법정동코드 → 행정동코드 JOIN
# ============================================================

result = df.merge(
    mapping_unique,
    on="법정동코드",
    how="left",
    suffixes=("", "_매핑")
)


# ============================================================
# 12. 행정동 매핑 결과 확인
# ============================================================

print("\n" + "=" * 60)
print("행정동 매핑 결과")
print("=" * 60)

print(
    f"전체 월세 데이터: {len(result):,}"
)

print(
    f"행정동 매칭 성공: "
    f"{result['행정동코드'].notna().sum():,}"
)

print(
    f"행정동 매칭 실패: "
    f"{result['행정동코드'].isna().sum():,}"
)


# ============================================================
# 13. 매칭률 계산
# ============================================================

total = len(result)

matched = result["행정동코드"].notna().sum()

match_rate = (
    matched / total * 100
    if total > 0
    else 0
)

print(
    f"\n행정동 매칭률: {match_rate:.2f}%"
)


# ============================================================
# 14. 매칭 실패 데이터 확인
# ============================================================

failed = result[
    result["행정동코드"].isna()
].copy()

print("\n[행정동 매칭 실패 법정동코드]")

print(
    failed[
        [
            "법정동코드",
            "법정동명"
        ]
    ]
    .drop_duplicates()
    .head(50)
)


# ============================================================
# 15. 매칭 실패 데이터 저장
# ============================================================

failed.to_csv(
    FAILED_FILE,
    index=False,
    encoding="utf-8-sig"
)


# ============================================================
# 16. 최종 컬럼 정리
# ============================================================

# 분석에 필요없는 매핑용 중복 컬럼이 있다면 제거
drop_columns = [
    "시도명",
    "시군구명"
]

for col in drop_columns:

    if col in result.columns:
        result.drop(
            columns=col,
            inplace=True
        )


# ============================================================
# 17. 최종 데이터 저장
# ============================================================

result.to_csv(
    OUTPUT_FILE,
    index=False,
    encoding="utf-8-sig"
)


# ============================================================
# 18. 최종 결과 출력
# ============================================================

print("\n" + "=" * 60)
print("완료!")
print("=" * 60)

print(
    f"최종 데이터: {OUTPUT_FILE}"
)

print(
    f"매칭 실패 데이터: {FAILED_FILE}"
)

print(
    f"최종 행 수: {len(result):,}"
)

print("\n[최종 데이터 예시]")

print(
    result[
        [
            "법정동코드",
            "법정동명",
            "행정동코드",
            "읍면동명"
        ]
    ].head(20)
)